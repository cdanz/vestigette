def main():
    import re

    lines = [
        "-- Brianna Barnes (profileID=2) — ENDORSEMENTS",
        "-- Generated by gen_brianna_endorsements.py",
        "",
        "-- ╔══════════════════════════════════════════════════════════╗",
        "-- ║  STEP 1: Fix PHRASE_ENDORSE for all Brianna phrasings   ║",
        "-- ╚══════════════════════════════════════════════════════════╝",
        "",
        "INSERT IGNORE INTO PHRASE_ENDORSE (argumentID, phrasingID, profileID, weight, active)",
        "SELECT p.argumentID, p.phrasingID, 2, 100, 1",
        "FROM PHRASING p",
        "WHERE p.coinedBy = 2",
        "  AND NOT EXISTS (",
        "    SELECT 1 FROM PHRASE_ENDORSE pe",
        "    WHERE pe.profileID = 2 AND pe.argumentID = p.argumentID",
        "  );",
        "",
        "-- ╔══════════════════════════════════════════════════════════╗",
        "-- ║  STEP 2: Endorsement chains by cluster                  ║",
        "-- ╚══════════════════════════════════════════════════════════╝",
        "",
    ]

    # Collect all unique targArgIDs and SQL rows across all clusters
    all_targets = set()
    all_sql_rows = []

    for cluster_name, g in CLUSTERS:
        cluster_rows = g.generate_sql_rows([])
        if not cluster_rows:
            continue
        cluster_targets = set(g.because_edges.keys()) | set(g.rebuttal_edges.keys())
        for targ in g._compute_therefore().keys():
            cluster_targets.add(targ)
        all_targets.update(cluster_targets)
        all_sql_rows.extend(cluster_rows)
        lines.append(f"-- ===== {cluster_name} =====")

    lines.append("")

    if all_targets:
        targ_list = ','.join(str(t) for t in sorted(all_targets))
        lines.append(f"DELETE FROM ENDORSEMENT WHERE profileID={PROFILE_ID} AND targArgID IN ({targ_list});")
        lines.append("")

    # Deduplicate: for each (targArgID, endorseType) GROUP, keep only rows
    # from the FIRST cluster that defines that group. This prevents weight
    # inflation when the same arg is defined in multiple clusters.
    seen_groups = set()   # tracks (targArgID, endorseType) pairs already claimed
    unique_rows = []

    # Re-generate rows cluster-by-cluster so we can claim groups in cluster order
    for _cluster_name, g in CLUSTERS:
        cluster_rows = g.generate_sql_rows([])
        # Collect rows by group for this cluster only
        from collections import defaultdict
        cg_rows = defaultdict(list)
        for row in cluster_rows:
            m = re.match(r'\((\d+),\d+,\'(\w+)\',(\d+),', row)
            if m:
                group_key = (m.group(1), m.group(2))
                cg_rows[group_key].append(row)
        # For each new group in this cluster, claim it and add its rows
        for group_key, rows_list in cg_rows.items():
            if group_key not in seen_groups:
                seen_groups.add(group_key)
                unique_rows.extend(rows_list)

    if unique_rows:
        lines.append("INSERT INTO ENDORSEMENT (targArgID,profileID,endorseType,supportingArgID,weight,active) VALUES")
        lines.append(",\n".join(unique_rows) + ";")

    lines.append("")
    lines.append("-- ╔══════════════════════════════════════════════════════════╗")
    lines.append("-- ║  STEP 3: Sync PHRASE_ENDORSE active flag                ║")
    lines.append("-- ╚══════════════════════════════════════════════════════════╝")
    lines.append("")
    lines.append("-- Set active=0 for phrasings of rejected args")
    lines.append("UPDATE PHRASE_ENDORSE pe")
    lines.append("JOIN OPINION o ON pe.argumentID = o.argumentID AND o.profileID = 2")
    lines.append("SET pe.active = o.acceptance")
    lines.append("WHERE pe.profileID = 2;")
    lines.append("")
    lines.append("SELECT 'Done: endorsements for profileID=2' AS status;")

    print('\n'.join(lines))


if __name__ == '__main__':
    main()
