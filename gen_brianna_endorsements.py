#!/usr/bin/env python3
"""
Generate endorsement SQL for Brianna Barnes (profileID=2).

Pattern:
  Because[A] includes B  → "I believe A because of B"
  Therefore[A] includes B → "A therefore B" (A implies B)
  Rebuttal[R] includes A  → "I rebut R because of my accepted arg A"

Weights per (targArgID, endorseType) group must sum to 100.
"""

PROFILE_ID = 2

# ─── helper ──────────────────────────────────────────────────────────────────

def norm(pairs):
    """Normalize weights to 100.  pairs = [(argID, raw_weight), ...]"""
    total = sum(w for _, w in pairs)
    result = [(a, round(w / total * 100, 5)) for a, w in pairs]
    # fix floating-point error on last element
    diff = 100.0 - sum(w for _, w in result)
    result[-1] = (result[-1][0], round(result[-1][1] + diff, 5))
    return result


def rows(targArgID, endorseType, pairs):
    """Return list of SQL INSERT rows."""
    out = []
    for supportingArgID, weight in norm(pairs):
        out.append(
            f"({targArgID},{PROFILE_ID},'{endorseType}',{supportingArgID},{weight},1)"
        )
    return out


# ─── endorsement graph builder ────────────────────────────────────────────────

class EndorsementGraph:
    def __init__(self):
        # because_edges[A] = [(B, weight), ...] means "A is supported by B"
        self.because_edges = {}   # targArgID -> [(supporting, weight)]
        # rebuttal_edges[R] = [(A, weight), ...] means "R is rebutted by A"
        self.rebuttal_edges = {}  # rejectedArgID -> [(accepted, weight)]

    def because(self, targ, supporters):
        """Add Because[targ] supported by list of (argID, weight)."""
        self.because_edges[targ] = supporters

    def rebuttal(self, targ, rebuters):
        """Add Rebuttal[targ] rebutted by list of (argID, weight)."""
        self.rebuttal_edges[targ] = rebuters

    def _compute_therefore(self):
        """Derive Therefore edges from Because edges (reversed direction)."""
        # For each A supported by B: Therefore[B] includes A
        therefore = {}  # B -> [(A, weight)]
        for targ, supporters in self.because_edges.items():
            for sup, w in supporters:
                therefore.setdefault(sup, []).append((targ, w))
        return therefore

    def generate_sql_rows(self, cluster_all_args):
        """Generate all SQL value rows for this cluster."""
        out = []
        # Because rows
        for targ, supporters in self.because_edges.items():
            out.extend(rows(targ, 'Because', supporters))
        # Therefore rows (derived)
        for targ, implies_list in self._compute_therefore().items():
            out.extend(rows(targ, 'Therefore', implies_list))
        # Rebuttal rows
        for targ, rebuters in self.rebuttal_edges.items():
            out.extend(rows(targ, 'Rebuttal', rebuters))
        return out


